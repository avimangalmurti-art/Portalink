// OS-only launch backgrounds, not replacements for the app's looping media.
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { crc32, deflateSync } from 'node:zlib';

// CSS device width/height and DPR; include older, mini, and current phone classes.
const devices = [
  [320, 568, 2], [375, 667, 2], [414, 736, 3], [360, 780, 3],
  [375, 812, 3], [414, 896, 2], [414, 896, 3], [390, 844, 3],
  [428, 926, 3], [393, 852, 3], [430, 932, 3], [402, 874, 3],
  [420, 912, 3], [440, 956, 3],
];
const directory = new URL('../public/startup/', import.meta.url);
mkdirSync(directory, { recursive: true });
function chunk(type, data) {
  const body = Buffer.concat([Buffer.from(type), data]);
  const size = Buffer.alloc(4), checksum = Buffer.alloc(4);
  size.writeUInt32BE(data.length); checksum.writeUInt32BE(crc32(body));
  return Buffer.concat([size, body, checksum]);
}
function png(width, height) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0); header.writeUInt32BE(height, 4);
  header[8] = 8; header[9] = 2; // 8-bit opaque RGB
  const row = Buffer.alloc(1 + width * 3);
  for (let x = 1; x < row.length; x += 3) row.set([248, 253, 252], x);
  const pixels = Buffer.alloc(row.length * height);
  for (let y = 0; y < height; y++) row.copy(pixels, y * row.length);
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', header), chunk('IDAT', deflateSync(pixels, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
const links = [];
for (const [deviceWidth, deviceHeight, dpr] of devices) {
  for (const orientation of ['portrait', 'landscape']) {
    const [width, height] = (orientation === 'portrait' ? [deviceWidth, deviceHeight] : [deviceHeight, deviceWidth]).map(value => value * dpr);
    const filename = `apple-startup-${width}x${height}.png`;
    writeFileSync(new URL(filename, directory), png(width, height));
    const media = `screen and (device-width: ${deviceWidth}px) and (device-height: ${deviceHeight}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: ${orientation})`;
    links.push(`    <link rel="apple-touch-startup-image" href="/startup/${filename}" media="${media}" />`);
  }
}
const html = new URL('../index.html', import.meta.url);
const source = readFileSync(html, 'utf8');
const start = '<!-- Apple startup backgrounds: generated by scripts/generate-apple-startup.mjs -->';
const end = '    <!-- End Apple startup backgrounds -->';
if (!source.includes(start) || !source.includes(end)) throw new Error('Missing startup-image insertion markers');
writeFileSync(html, source.slice(0, source.indexOf(start)) + start + '\n' + links.join('\n') + '\n' + source.slice(source.indexOf(end)));
