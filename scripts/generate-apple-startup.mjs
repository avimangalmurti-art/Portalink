// Manual OS launch-image regeneration from the app's unchanged first frame.
// Normal app builds consume these checked-in PNGs and never require FFmpeg.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const { values } = parseArgs({ options: { ffmpeg: { type: 'string' }, 'assets-only': { type: 'boolean', default: false } } });
const ffmpeg = values.ffmpeg || process.env.PORTALINK_STARTUP_FFMPEG || 'ffmpeg';
const poster = new URL('../public/portalink-splash-poster.png', import.meta.url);
const posterPath = fileURLToPath(poster);
const posterBytes = readFileSync(poster);
if (posterBytes.readUInt32BE(16) !== 512 || posterBytes.readUInt32BE(20) !== 720) throw new Error('Expected the existing 512x720 splash first frame.');

// CSS device width/height and DPR; include older, mini, and current phone classes.
const devices = [
  [320, 568, 2], [375, 667, 2], [414, 736, 3], [360, 780, 3],
  [375, 812, 3], [414, 896, 2], [414, 896, 3], [390, 844, 3],
  [428, 926, 3], [393, 852, 3], [430, 932, 3], [402, 874, 3],
  [420, 912, 3], [440, 956, 3],
];
const directory = new URL('../public/startup/', import.meta.url);
mkdirSync(directory, { recursive: true });
function render(width, height, destination) {
  const result = spawnSync(ffmpeg, [
    '-hide_banner', '-loglevel', 'error', '-y', '-i', posterPath,
    '-vf', `scale=${width}:${height}:force_original_aspect_ratio=decrease:flags=lanczos,setsar=1,pad=${width}:${height}:(ow-iw)/2:(oh-ih)/2:color=0xfdffff,format=rgb24`,
    '-map_metadata', '-1', '-frames:v', '1', '-update', '1', '-threads', '1', '-compression_level', '9', '-pred', 'mixed', fileURLToPath(destination),
  ], { windowsHide: true, encoding: 'utf8', maxBuffer: 1024 * 1024 });
  if (result.error) throw new Error('FFmpeg could not start. Supply --ffmpeg or PORTALINK_STARTUP_FFMPEG.', { cause: result.error });
  if (result.status !== 0) throw new Error(`Startup image ${width}x${height} could not render: ${result.stderr.trim()}`);
}
const links = [];
for (const [deviceWidth, deviceHeight, dpr] of devices) {
  for (const orientation of ['portrait', 'landscape']) {
    const [width, height] = (orientation === 'portrait' ? [deviceWidth, deviceHeight] : [deviceHeight, deviceWidth]).map(value => value * dpr);
    const filename = `apple-startup-${width}x${height}.png`;
    const destination = new URL(filename, directory);
    render(width, height, destination);
    const revision = createHash('sha256').update(readFileSync(destination)).digest('hex').slice(0, 12);
    const media = `screen and (device-width: ${deviceWidth}px) and (device-height: ${deviceHeight}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: ${orientation})`;
    links.push(`    <link rel="apple-touch-startup-image" href="/startup/${filename}?v=${revision}" media="${media}" />`);
  }
}
if (!values['assets-only']) {
  const html = new URL('../index.html', import.meta.url);
  const source = readFileSync(html, 'utf8');
  const start = '<!-- Apple startup backgrounds: generated by scripts/generate-apple-startup.mjs -->';
  const end = '    <!-- End Apple startup backgrounds -->';
  if (!source.includes(start) || !source.includes(end)) throw new Error('Missing startup-image insertion markers');
  writeFileSync(html, source.slice(0, source.indexOf(start)) + start + '\n' + links.join('\n') + '\n' + source.slice(source.indexOf(end)));
}
process.stdout.write(`Rendered ${links.length} opaque startup images from the existing splash first frame${values['assets-only'] ? '; HTML unchanged' : '; startup URLs revised'}.\n`);
