// Keep the HTML first paint and React fallback identical, without an image request.
// Pass --ffmpeg <executable> when regenerating after changing the supplied poster.
import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const asset = new URL('../public/portalink-splash-first-frame.webp', import.meta.url);
const ffmpegIndex = process.argv.indexOf('--ffmpeg');
if (ffmpegIndex !== -1) {
  const executable = process.argv[ffmpegIndex + 1];
  if (!executable) throw new Error('Pass the ffmpeg executable after --ffmpeg');
  const result = spawnSync(executable, ['-hide_banner', '-loglevel', 'error', '-y', '-i', fileURLToPath(new URL('../public/portalink-splash-poster.png', import.meta.url)), '-frames:v', '1', '-c:v', 'libwebp', '-q:v', '90', '-compression_level', '6', fileURLToPath(asset)], { windowsHide: true, encoding: 'utf8' });
  if (result.status !== 0) throw new Error('Splash first-frame conversion failed');
}
const bytes = readFileSync(asset);
if (bytes.length > 24000 || bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') throw new Error('Expected a small WebP first frame');
const dataUrl = `data:image/webp;base64,${bytes.toString('base64')}`;
writeFileSync(new URL('../src/components/ui/splashPoster.ts', import.meta.url), `// Generated by scripts/generate-splash-poster.mjs from the supplied clip's first frame.\nexport const SPLASH_POSTER_DATA_URL = '${dataUrl}';\n`);
const htmlPath = new URL('../index.html', import.meta.url);
const html = readFileSync(htmlPath, 'utf8');
const picture = /<picture(?: data-portalink-inline-splash)?>([\s\S]*?)<\/picture>/;
if (!picture.test(html)) throw new Error('Missing startup picture');
const manifestHash = createHash('sha256').update(readFileSync(new URL('../public/site.webmanifest', import.meta.url))).digest('hex').slice(0, 8);
const updated = html.replace(picture, `<picture data-portalink-inline-splash>\n          <img src="${dataUrl}" alt="" aria-hidden="true" width="512" height="720" decoding="sync" fetchpriority="high" />\n        </picture>`).replace('WEB retains its first frame; MOBILE repeats the supplied animation.', 'The supplied first frame is visible before JavaScript or external media downloads.').replace(/href="\/site\.webmanifest\?v=[^"]+"/, `href="/site.webmanifest?v=${manifestHash}"`);
writeFileSync(htmlPath, updated);
console.log(JSON.stringify({ bytes: bytes.length, hash: createHash('sha256').update(bytes).digest('hex').slice(0, 8) }));
